    internal static Dictionary<int, string[]> Build(IEnumerable<KeyValuePair<string, string>> entries)
    {
        var groups = new Dictionary<int, HashSet<string>>();
        foreach (var pair in entries)
        {
            if (!Enum.TryParse(pair.Value, out swCommands_e value) || !Enum.IsDefined(typeof(swCommands_e), pair.Value)) continue;
            int id = (int)value;
            if (id < 0 || string.IsNullOrWhiteSpace(pair.Key)) continue;
            if (!groups.TryGetValue(id, out var symbols)) groups[id] = symbols = new HashSet<string>(StringComparer.Ordinal);
            symbols.Add(pair.Key);
        }
        return groups.ToDictionary(pair => pair.Key, pair => pair.Value.OrderBy(symbol => symbol, StringComparer.Ordinal).ToArray());
    }
