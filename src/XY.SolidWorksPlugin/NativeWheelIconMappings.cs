        new KeyValuePair<string, string>("swCommands_SaveAs", "PNG_STANDARD_SAVEAS_40"),
    };

    internal static readonly IReadOnlyDictionary<int, string> Resources = Build();

    internal static bool TryGetBasicCommandId(string action, out int id)
    {
        string name = action switch
        {
            "new-part" or "new-assembly" or "new-drawing" => "swCommands_New",
            "rebuild" => "swCommands_Rebuild",
            "force-rebuild" => "swCommands__Force_Rebuild",
            "normal-to" => "swCommands_NormalTo",
            "zoom-fit" => "swCommands_ZoomToFit",
            "view-front" => "swCommands_Front",
            "view-back" => "swCommands_Back",
            "view-left" => "swCommands_Left",
            "view-right" => "swCommands_Right",
            "view-top" => "swCommands_Top",
            "view-bottom" => "swCommands_Bottom",
            "view-isometric" => "swCommands_Isometric",
            "explode-all" => "swCommands_ExplodedView",
            _ => ""
        };
        bool found = name.Length > 0 && Enum.TryParse(name, out swCommands_e command);
        id = found ? Convert.ToInt32(Enum.Parse(typeof(swCommands_e), name)) : -1;
        return found;
    }

    private static Dictionary<int, string> Build()
    {
        var resolved = Entries.Select(pair => new
        {
            Valid = Enum.TryParse(pair.Key, out swCommands_e command),
            Id = Enum.TryParse(pair.Key, out swCommands_e value) ? (int)value : -1,
            Resource = pair.Value
        }).Where(pair => pair.Valid && pair.Id >= 0);
        // Aliases which disagree about artwork are not authoritative. A live
        // toolbar image remains available as the fallback for these identities.
        return resolved.GroupBy(pair => pair.Id)
            .Where(group => group.Select(pair => pair.Resource).Distinct(StringComparer.Ordinal).Count() == 1)
            .ToDictionary(group => group.Key, group => group.First().Resource);
    }
